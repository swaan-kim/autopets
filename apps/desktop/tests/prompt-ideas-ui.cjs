const assert = require('node:assert/strict');
const path = require('node:path');
const template = require('../../../packages/contracts/data/ui-pet.json');
const { openCatalog } = require('./entry-navigation.cjs');
const { runPromptVideoChecks } = require('./prompt-video-ui.cjs');

exports.runPromptIdeaChecks = async ({ newPage, mockBridge, fixture, origin, screenshotDir, checks }) => {
  const link = { version: 1, target: { sourceId: 'codex-windows-local', threadId: '11111111-2222-4333-8444-555555555555', cwd: 'C:/UI fixture only A' }, slot: 0, revision: 1, enabled: true, connected: true, profile: 'light', template, run: null };
  const other = { ...structuredClone(link), target: { ...link.target, threadId: '22222222-2222-4333-8444-555555555555', cwd: 'C:/UI fixture only B' }, slot: 1, connected: false };
  const page = await newPage({ width: 992, height: 688 });
  const state = { ...structuredClone(fixture), sessions: [], slots: [], petLinks: [link, other], setup: { version: 1, appReady: true, connectionMode: 'explicit-pet', connections: [{ hostId: 'codex-windows-local', configured: true }] } };
  await mockBridge(page, state); await page.goto(origin);
  await page.getByRole('heading', { name: '내 작업', exact: true }).waitFor();
  assert.equal(await page.locator('.pet-home').count(), 0, 'existing work is the entry point');
  await openCatalog(page);
  const ideas = page.getByRole('region', { name: '이미지와 영상 아이디어', exact: true });
  assert.equal(await ideas.locator('.prompt-idea-card').count(), 4);
  await page.waitForFunction(() => [...document.querySelectorAll('.prompt-idea-card .ux-art-generated')].length === 2
    && [...document.querySelectorAll('.prompt-idea-card .ux-art-generated')].every(image => image.complete && image.naturalWidth === 1536 && image.naturalHeight === 1024));
  assert.equal(await ideas.locator('[data-evidence="public-ai-video"]').count(), 2);
  assert.equal(await ideas.locator('.ux-art-play').count(), 2, 'play badges open real bundled video previews');
  await ideas.getByRole('button', { name: '영상 예시', exact: true }).click();
  assert.equal(await ideas.locator('.prompt-idea-card').count(), 2);
  await ideas.getByRole('button', { name: '이미지 예시', exact: true }).click();
  const trigger = ideas.getByRole('button', { name: '작은 브랜드의 제품 사진 예시 살펴보기', exact: true });
  await trigger.click();
  const dialog = page.getByRole('dialog', { name: '작은 브랜드의 제품 사진', exact: true });
  await dialog.waitFor();
  const previewBeforeExpansion = await dialog.locator('.ux-art-generated').boundingBox();
  const detailBeforeExpansion = await dialog.locator('.prompt-idea-detail').boundingBox();
  await dialog.getByText('3:2 가로 구도', { exact: true }).waitFor();
  await dialog.getByText('이 이미지를 만든 프롬프트', { exact: true }).click();
  const previewAfterExpansion = await dialog.locator('.ux-art-generated').boundingBox();
  const detailAfterExpansion = await dialog.locator('.prompt-idea-detail').boundingBox();
  assert.ok(Math.abs((previewAfterExpansion.y - detailAfterExpansion.y) - (previewBeforeExpansion.y - detailBeforeExpansion.y)) <= 1, 'expanding the source prompt keeps the result image aligned with the explanation');
  assert.ok(previewAfterExpansion.y < 688 / 2, 'the result preview remains visible beside the expanded prompt');
  assert.match(await dialog.locator('.prompt-idea-source pre').textContent(), /sage green frosted glass/);
  assert.match(await dialog.locator('.prompt-idea-source').textContent(), /1536×1024/);
  await page.keyboard.press('Escape'); await dialog.waitFor({ state: 'hidden' });
  assert.equal(await trigger.evaluate(element => element === document.activeElement), true);
  await trigger.click(); await dialog.getByRole('button', { name: /이 방식으로 펫 준비/ }).click();
  const composer = page.locator('.pet-composer');
  await composer.getByRole('heading', { name: '이미지 프롬프트 만들기', exact: true }).waitFor();
  assert.equal(await composer.getByLabel('UI 펫을 적용할 채팅', { exact: true }).inputValue(), JSON.stringify([link.target.sourceId, link.target.threadId, link.target.cwd]), 'the only eligible conversation is preselected without retargeting to disconnected B');
  assert.equal(await composer.locator('.composer-copy-fallback').evaluate(element => element.open), false, 'using an idea never opens a copy gate');
  assert.deepEqual(await page.evaluate(() => window.__uiTest.calls), [], 'browsing and choosing an idea do not connect, save, or execute');
  await composer.getByRole('button', { name: /이 채팅에 펫 적용/ }).click();
  await composer.locator('.composer-applied').waitFor();
  const result = await page.evaluate(() => ({ calls: window.__uiTest.calls, pets: window.__uiTest.roles.pets, links: window.__uiTest.state.petLinks, clipboard: window.__uiTest.clipboard }));
  assert.equal(result.pets.length, 1);
  assert.match(result.pets[0].template.instruction, /크림색 배경/);
  assert.equal(result.pets[0].template.id, 'research-document', 'the idea reuses the existing bounded role contract');
  assert.deepEqual(result.pets[0].template.skills, [{ id: 'autopets-research-document', version: '1.0.0' }]);
  assert.ok(Buffer.byteLength(result.pets[0].template.instruction, 'utf8') <= 1536);
  assert.deepEqual(result.links[1], other);
  assert.equal(result.clipboard, '');
  assert.match(result.calls.find(call => call.name === 'save_pet').args.template.instruction, /기본 조건: 3:2 가로 구도 · 자연광 · 제품 사진/);
  assert.equal(result.calls.filter(call => call.name === 'apply_pet_link_template').length, 1);
  await composer.getByRole('button', { name: 'Codex 작업 열기', exact: true }).click();
  await composer.getByText(/Codex에 열기를 요청했어요/).waitFor();
  assert.deepEqual(await page.evaluate(() => window.__uiTest.calls.filter(call => call.name === 'open_pet_task').map(call => call.args.target)), [link.target]);
  assert.equal(await page.evaluate(() => window.__uiTest.calls.some(call => /submit|execute|delegate|send/.test(call.name))), false);
  await openCatalog(page);
  await ideas.getByRole('button', { name: '전체 예시', exact: true }).click();
  const shots = [];
  for (const [width, height] of [[992, 688], [390, 844], [320, 740]]) {
    await page.setViewportSize({ width, height });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    const file = path.join(screenshotDir, `prompt-ideas-${width}.png`); await page.screenshot({ path: file, fullPage: true, animations: 'disabled' }); shots.push(file);
  }
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await ideas.getByRole('button', { name: '호수 위의 느린 오후 예시 살펴보기', exact: true }).click();
  assert.equal(await page.locator('.prompt-idea-dialog video').evaluate(element => element.paused), true, 'reduced motion does not start playback');
  await page.close();
  const fallback = await newPage();
  await mockBridge(fallback, state);
  await fallback.route('**/prompt-gallery-v1/product.webp', route => route.abort());
  await fallback.route('**/prompt-videos-v1/swans-poster.webp', route => route.abort());
  await fallback.goto(origin); await openCatalog(fallback);
  await fallback.locator('[data-agent-id="pet-selection.idea.product"] [data-evidence="design-example"] svg').waitFor();
  assert.equal(await fallback.locator('[data-agent-id="pet-selection.idea.product"] .ux-art-generated').count(), 0);
  const videoFallback = fallback.locator('[data-agent-id="pet-selection.idea.coast"]');
  await videoFallback.locator('.ux-art-video-placeholder').waitFor();
  assert.equal(await videoFallback.locator('.ux-art-evidence').textContent(), 'AI 영상 · 6초');
  await fallback.close();
  checks.push('result ideas filter image/video, preserve dialog focus, apply a bounded pinned-role preset without clipboard, preselect only eligible A, preserve B, and return to the exact existing conversation without submitting an AI request; 320/390/992px and reduced motion');
  checks.push('two generated image examples and two public AI video posters are distinct; exact image production prompts remain inspectable; missing image/poster assets have explicit fallbacks');
  await runPromptVideoChecks({ newPage, mockBridge, state, origin, checks });
  return shots;
};
