const assert = require('node:assert/strict');
const path = require('node:path');
const template = require('../../../packages/contracts/data/ui-pet.json');
const KEY = 'autopets.pet-favorites.v1';

exports.runPetDiscoveryChecks = async ({ newPage, mockBridge, fixture, origin, screenshotDir, checks }) => {
  const page = await newPage({ width: 992, height: 688 });
  await mockBridge(page, { ...structuredClone(fixture), sessions: [], slots: [], petLinks: [], setup: { version: 1, connectionMode: 'explicit-pet', connections: [{ hostId: 'codex-windows-local', configured: true }] } });
  await page.addInitScript(template => { window.__uiTest.roles.pets = [{ id: 'favorite-standard', revision: 2, template: { ...template, execution: { model: 'gpt-6-sol', reasoning: 'low' } } }]; }, template);
  await page.goto(origin);
  const wizard = page.locator('.ui-pet-wizard');
  const favorite = wizard.getByRole('button', { name: 'UI 제작 펫 즐겨찾기', exact: true });
  await favorite.waitFor();
  await page.getByRole('region', { name: '사용 전후 예시', exact: true }).waitFor();
  await wizard.locator('.pet-sprite').waitFor();
  const introductionImage = path.join(screenshotDir, 'pet-discovery-introduction.png');
  await page.screenshot({ path: introductionImage, fullPage: true });
  await page.setViewportSize({ width: 992, height: 550 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  const comparisonImage = path.join(screenshotDir, 'pet-discovery-comparison.png');
  await page.screenshot({ path: comparisonImage, fullPage: true });
  await page.setViewportSize({ width: 992, height: 688 });
  assert.equal(await favorite.getAttribute('aria-pressed'), 'false');
  await favorite.click();
  assert.equal(await favorite.getAttribute('aria-pressed'), 'true');
  assert.deepEqual(await page.evaluate(key => JSON.parse(localStorage.getItem(key)), KEY), { version: 1, ids: ['template:ui-webpage'] });
  assert.deepEqual(await page.evaluate(() => window.__uiTest.calls), []);
  await page.reload();
  await favorite.waitFor();
  await page.waitForFunction(() => document.querySelector('.pet-favorite-button')?.getAttribute('aria-pressed') === 'true');
  await wizard.getByRole('button', { name: '펫 준비 닫기', exact: true }).click();
  const shelf = page.getByRole('region', { name: '즐겨찾는 펫', exact: true });
  await shelf.getByRole('button', { name: '이 펫 부르기', exact: true }).click();
  assert.equal(await wizard.getAttribute('data-step'), '1');
  await wizard.getByText('모델과 저장한 구성', { exact: true }).click();
  await wizard.getByLabel('저장한 구성', { exact: true }).selectOption('favorite-standard');
  await favorite.click();
  await wizard.getByRole('button', { name: '펫 준비 닫기', exact: true }).click();
  assert.equal(await shelf.locator('article').count(), 2);
  await page.reload();
  await wizard.getByRole('button', { name: '펫 준비 닫기', exact: true }).click();
  const standard = shelf.locator('article').filter({ hasText: '표준 · 기본 제작' });
  await standard.getByRole('button', { name: '이 펫 부르기', exact: true }).click();
  assert.equal(await wizard.getAttribute('data-step'), '3');
  assert.deepEqual(await page.evaluate(() => window.__uiTest.calls), []);
  const task = wizard.getByRole('textbox', { name: '펫에게 맡길 일', exact: true });
  await task.fill('');
  assert.equal(await wizard.getByRole('button', { name: '시작 요청 복사', exact: true }).isDisabled(), true);
  const request = '도예 작품 포트폴리오를 만들고 싶어요.\n작품 3개와 소개, 연락 방법을 담아줘.';
  await task.fill(request);
  const requestImage = path.join(screenshotDir, 'pet-discovery-request.png');
  await page.setViewportSize({ width: 992, height: 550 });
  await wizard.locator('.pet-sprite').waitFor();
  await page.screenshot({ path: requestImage, fullPage: true });
  await page.setViewportSize({ width: 992, height: 688 });
  await wizard.getByRole('button', { name: '← 이전', exact: true }).click();
  await wizard.getByRole('button', { name: '채팅에서 시작하기', exact: true }).click();
  assert.equal(await task.inputValue(), request);
  await wizard.getByRole('button', { name: '시작 요청 복사', exact: true }).click();
  await wizard.getByText('복사했어요. 사용할 Codex 채팅에 붙여넣고 보내주세요.', { exact: true }).waitFor();
  const copied = await page.evaluate(() => window.__uiTest.clipboard);
  assert.ok(copied.includes(request));
  assert.ok(copied.includes('petId=favorite-standard, petRevision=2'));
  assert.ok(copied.includes('계획만 세워줘'));
  assert.ok(copied.includes('내 구현 요청을 기다려줘'));
  assert.ok(!copied.includes('학과 행사') && !copied.includes('autopets-demo'));
  assert.deepEqual(await page.evaluate(() => window.__uiTest.calls), []);
  assert.equal(await page.evaluate(() => window.__uiTest.state.petLinks.length), 0);
  await wizard.getByText('채팅 연결 대기 · 복사는 아직 전송이 아니에요.', { exact: true }).waitFor();
  await task.fill('새로운 요청');
  assert.equal(await wizard.getByLabel('Codex에 보낼 시작 요청', { exact: true }).count(), 0);
  assert.equal(await wizard.getByRole('button', { name: '시작 요청 복사', exact: true }).count(), 1);
  await wizard.getByRole('button', { name: '행사 페이지 예시로 시작', exact: true }).click();
  await wizard.getByRole('button', { name: '시작 요청 복사', exact: true }).click();
  assert.ok((await page.evaluate(() => window.__uiTest.clipboard)).includes('autopets-demo'));
  checks.push('pet/template favorites persist across reload, saved favorites restore exact current configuration without applying/executing; custom Korean multiline requests preserve text and plan-first instructions, blank/edited requests cannot reuse stale copy feedback');

  await wizard.getByRole('button', { name: '펫 준비 닫기', exact: true }).click();
  const shelfImage = path.join(screenshotDir, 'pet-discovery-favorites.png');
  await shelf.locator('.pet-sprite').first().waitFor();
  await shelf.locator('.pet-sprite').last().waitFor();
  await page.screenshot({ path: shelfImage, fullPage: true });
  await page.evaluate(() => { window.__uiTest.roles.pets = []; window.__uiTest.emitEvent('autopets://roles-changed', {}); });
  const missing = shelf.locator('article').filter({ hasText: '찾을 수 없는 펫' });
  await missing.waitFor();
  assert.equal(await missing.getByRole('button', { name: '이 펫 부르기', exact: true }).isDisabled(), true);
  await missing.getByRole('button', { name: 'UI 제작 펫 즐겨찾기 해제', exact: true }).click();
  assert.equal(await shelf.locator('article').count(), 1);
  await page.evaluate(key => { localStorage.setItem(key, '{broken'); window.dispatchEvent(new StorageEvent('storage', { key })); }, KEY);
  await shelf.getByRole('button', { name: 'UI 제작 펫 즐겨찾기 해제', exact: true }).click();
  await shelf.getByRole('alert').filter({ hasText: '즐겨찾기를 저장하지 못했어요' }).waitFor();
  assert.equal(await page.evaluate(key => localStorage.getItem(key), KEY), '{broken');
  await page.evaluate(key => { localStorage.removeItem(key); window.dispatchEvent(new StorageEvent('storage', { key })); }, KEY);
  await shelf.getByText(/마음에 드는 펫에/).waitFor();
  await page.getByRole('button', { name: '펫 준비', exact: true }).click();
  await wizard.getByRole('button', { name: '← 이전', exact: true }).click();
  await wizard.getByRole('button', { name: '← 이전', exact: true }).click();
  await page.evaluate(() => { Storage.prototype.setItem = () => { throw Error('fixture storage unavailable'); }; });
  await favorite.click();
  await wizard.getByRole('alert').filter({ hasText: '즐겨찾기를 저장하지 못했어요' }).waitFor();
  assert.equal(await favorite.getAttribute('aria-pressed'), 'false');
  checks.push('missing saved favorites cannot open; malformed/unavailable storage never reports a successful favorite or overwrites corrupt preferences; UI-only favorites never change chat state');
  return [introductionImage, comparisonImage, requestImage, shelfImage];
};
