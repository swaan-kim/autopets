const assert = require('node:assert/strict');
const path = require('node:path');
const template = require('../../../packages/contracts/data/ui-pet.json');
const KEY = 'autopets.pet-favorites.v1';
exports.runPetDiscoveryChecks = async ({newPage,mockBridge,fixture,origin,screenshotDir,checks}) => {
 const page=await newPage({width:992,height:688});
 await mockBridge(page,{...structuredClone(fixture),sessions:[],slots:[],petLinks:[],setup:{version:1,connectionMode:'explicit-pet',connections:[{hostId:'codex-windows-local',configured:true}]}});
 await page.addInitScript(template=>{window.__uiTest.roles.pets=[{id:'favorite-standard',revision:2,template:{...template,execution:{model:'gpt-6-sol',reasoning:'low'}}}];},template);
 await page.goto(origin);
 const favorite=page.locator('.workspace-role-card').getByRole('button',{name:'웹페이지 만들기 즐겨찾기',exact:true});
 await favorite.click(); assert.equal(await favorite.getAttribute('aria-pressed'),'true');
 assert.deepEqual(await page.evaluate(key=>JSON.parse(localStorage.getItem(key)),KEY),{version:1,ids:['template:ui-webpage']});
 await page.reload(); await favorite.waitFor(); assert.equal(await favorite.getAttribute('aria-pressed'),'true');
 await page.getByRole('button',{name:'내 펫',exact:true}).click();
 const shelf=page.getByRole('region',{name:'즐겨찾는 펫',exact:true});
 await shelf.getByRole('button',{name:'이 펫 부르기 →',exact:true}).click();
 const flow=page.locator('.pet-composer');
 await flow.getByText('저장한 구성과 연결 관리',{exact:true}).click();
 await flow.getByLabel('저장한 구성',{exact:true}).selectOption('favorite-standard');
 assert.equal(await flow.locator('input[aria-label="표준"]').isChecked(),true);
 await flow.getByRole('button',{name:'웹페이지 만들기 즐겨찾기',exact:true}).click();
 await flow.getByLabel('펫에게 맡길 일',{exact:true}).fill('');
 assert.equal(await flow.getByRole('button',{name:'시작 요청 복사',exact:true}).isDisabled(),true);
 const request='도예 작품 포트폴리오를 만들고 싶어요.\n작품 3개와 소개, 연락 방법을 담아줘.';
 await flow.getByLabel('펫에게 맡길 일',{exact:true}).fill(request);
 await flow.getByRole('button',{name:'시작 요청 복사',exact:true}).click();
 await flow.getByText('복사했어요. 사용할 Codex 채팅에 붙여넣고 보내주세요.',{exact:true}).waitFor();
 const copied=await page.evaluate(()=>window.__uiTest.clipboard);
 assert.ok(copied.includes(request)); assert.ok(copied.includes('petId=favorite-standard, petRevision=2')); assert.ok(!copied.includes('autopets-demo'));
 assert.deepEqual(await page.evaluate(()=>window.__uiTest.calls),[]);
 await flow.getByLabel('펫에게 맡길 일',{exact:true}).fill('새로운 요청'); assert.equal(await flow.getByLabel('Codex에 보낼 시작 요청',{exact:true}).count(),0);
 await flow.getByRole('button',{name:'← 펫 목록',exact:true}).click();
 const image=path.join(screenshotDir,'ux-v2-my-pets.png'); await page.screenshot({path:image,fullPage:true});
 await page.reload(); await page.getByRole('button',{name:'내 펫',exact:true}).click();
 const saved=shelf.locator('article').filter({has:page.getByRole('button',{name:'UI 제작 펫 즐겨찾기',exact:true})}).last();
 await saved.getByRole('button',{name:'이 펫 부르기 →',exact:true}).click();
 assert.equal(await flow.locator('input[aria-label="표준"]').isChecked(),true);
 assert.equal(await flow.getByRole('button',{name:'Codex에 펫 준비',exact:true}).count(),0);
 await flow.getByRole('button',{name:'← 펫 목록',exact:true}).click();
 await page.evaluate(()=>{window.__uiTest.roles.pets=[];window.__uiTest.emitEvent('autopets://roles-changed',{});});
 const missing=shelf.locator('article').filter({hasText:'찾을 수 없는 펫'}); await missing.waitFor();
 assert.equal(await missing.getByRole('button',{name:'이 펫 부르기 →',exact:true}).isDisabled(),true);
 await missing.getByRole('button',{name:'펫 즐겨찾기',exact:true}).click();
 await page.evaluate(key=>{localStorage.setItem(key,'{broken');window.dispatchEvent(new StorageEvent('storage',{key}));},KEY);
 await shelf.locator('.pet-favorite-button').click();
 await page.getByRole('alert').filter({hasText:'즐겨찾기를 저장하지 못했어요'}).waitFor();
 assert.equal(await page.evaluate(key=>localStorage.getItem(key),KEY),'{broken');
 await page.evaluate(key=>{localStorage.removeItem(key);window.dispatchEvent(new StorageEvent('storage',{key}));},KEY);
 await shelf.getByText('마음에 드는 펫에 ☆를 눌러보세요.',{exact:true}).waitFor();
 checks.push('favorites reload and saved revisions reuse without setup/save/apply; custom task preserves multiline request; missing/corrupt favorites remain recoverable and never mutate chat');
 await page.close(); return [image];
};
