const assert = require('node:assert/strict');
const { openCatalog } = require('./entry-navigation.cjs');

exports.runPromptVideoChecks = async ({ newPage, mockBridge, state, origin, checks }) => {
  const page = await newPage({ width: 992, height: 688 });
  const requests = [];
  page.on('request', request => requests.push(request.url()));
  await mockBridge(page, structuredClone(state));
  await page.goto(origin); await openCatalog(page);
  const region = page.getByRole('region', { name: '이미지와 영상 아이디어', exact: true });
  assert.equal(await region.locator('video').count(), 0, 'the grid does not create hidden video players');
  await region.getByRole('button', { name: '영상 예시', exact: true }).click();
  for (const [id, duration, model] of [['coast', 6.125, 'CogVideoX'], ['orbit', 5.64, 'Hailuo AI']]) {
    const trigger = region.locator(`[data-agent-id="pet-selection.idea.${id}"]`);
    await trigger.click();
    const dialog = page.locator('.prompt-idea-dialog');
    const video = dialog.locator('video');
    assert.equal(await video.getAttribute('preload'), 'none');
    assert.equal(await video.evaluate(element => element.paused && !element.autoplay && element.controls && element.muted), true);
    if (id === 'coast') assert.equal(requests.filter(url => /\.webm(?:\?|$)/.test(url)).length, 0, 'opening the first preview does not download a movie');
    await video.evaluate(element => element.play());
    await page.waitForFunction(() => document.querySelector('.prompt-idea-dialog video')?.currentTime > .25);
    assert.ok(Math.abs(await video.evaluate(element => element.duration) - duration) < .05, 'the real clip decodes at its recorded duration');
    await video.evaluate(element => element.pause());
    assert.equal(await video.evaluate(element => element.paused), true);
    await dialog.getByText('영상 출처', { exact: true }).click();
    assert.match(await dialog.locator('.prompt-idea-source').textContent(), new RegExp(model));
    assert.match(await dialog.locator('.prompt-idea-source').textContent(), /VulcanSphere.*CC0/);
    assert.match(await dialog.getByRole('link', { name: '원본 영상과 프롬프트 ↗' }).getAttribute('href'), /^https:\/\/commons\.wikimedia\.org\/wiki\/File:/);
    await video.evaluate(element => element.play());
    await page.evaluate(() => {
      Object.defineProperty(document, 'hidden', { configurable: true, value: true });
      document.dispatchEvent(new Event('visibilitychange'));
    });
    assert.equal(await video.evaluate(element => element.paused), true, 'the visibility event stops playback');
    await page.evaluate(() => { delete document.hidden; document.dispatchEvent(new Event('visibilitychange')); });
    assert.equal(await video.evaluate(element => element.paused), true, 'returning never starts the movie again');
    await video.evaluate(element => element.play());
    const detached = await video.elementHandle();
    await page.keyboard.press('Escape'); await dialog.waitFor({ state: 'hidden' });
    assert.equal(await detached.evaluate(element => element.paused), true, 'closing the dialog stops its detached player');
    assert.equal(await trigger.evaluate(element => element === document.activeElement), true);
    await detached.dispose();
  }
  await page.setViewportSize({ width: 375, height: 812 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await region.locator('[data-agent-id="pet-selection.idea.coast"]').click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  const playerBox = await page.locator('.prompt-idea-dialog video').boundingBox();
  assert.ok(playerBox.x >= 0 && playerBox.x + playerBox.width <= 375);
  assert.equal(await page.locator('.prompt-idea-dialog video').evaluate(element => element.paused), true);
  await page.getByRole('button', { name: /이 방식으로 펫 준비/ }).click();
  const composer = page.locator('.pet-composer');
  await composer.getByRole('heading', { name: '영상 프롬프트 만들기', exact: true }).waitFor();
  await composer.getByRole('button', { name: /이 채팅에 펫 적용/ }).click();
  await composer.locator('.composer-applied').waitFor();
  const result = await page.evaluate(() => ({ calls: window.__uiTest.calls, pets: window.__uiTest.roles.pets, clipboard: window.__uiTest.clipboard, links: window.__uiTest.state.petLinks }));
  assert.match(result.pets[0].template.instruction, /백조.*잔물결/);
  assert.equal(result.pets[0].template.id, 'research-document');
  assert.ok(Buffer.byteLength(result.pets[0].template.instruction, 'utf8') <= 1536);
  assert.equal(result.clipboard, '');
  assert.deepEqual(result.links[1], state.petLinks[1]);
  assert.equal(result.calls.filter(call => call.name === 'apply_pet_link_template').length, 1);
  assert.equal(result.calls.some(call => /submit|execute|delegate|send/.test(call.name)), false);
  assert.equal(requests.some(url => /^https?:/.test(url) && new URL(url).origin !== new URL(origin).origin), false, 'viewing and playing the bundled videos makes no external request');
  await page.close();

  const broken = await newPage();
  await mockBridge(broken, structuredClone(state));
  await broken.route('**/prompt-videos-v1/swans.webm', route => route.abort());
  await broken.goto(origin); await openCatalog(broken);
  await broken.locator('[data-agent-id="pet-selection.idea.coast"]').click();
  await broken.locator('.prompt-idea-dialog video').evaluate(element => element.play().catch(() => {}));
  await broken.getByRole('status').filter({ hasText: '영상을 재생할 수 없어요.' }).waitFor();
  assert.equal(await broken.locator('.prompt-idea-dialog img').count(), 1);
  await broken.getByRole('button', { name: /이 방식으로 펫 준비/ }).click();
  await broken.locator('.pet-composer').getByRole('heading', { name: '영상 프롬프트 만들기', exact: true }).waitFor();
  await broken.close();
  checks.push('two real local AI videos decode/play/pause; no autoplay or movie fetch on first open; close/visibility stop with no automatic resume; source attribution, 375px reduced motion, missing video/poster recovery, bounded preset applies only A without clipboard or AI execution, and no external media request');
};
